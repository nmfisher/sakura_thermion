/// Appends centred 16-pixel lettering in the local XY plane, facing +Z.
void appendPixelText(List<Part> out, String text,
    {required double x,
    required double y,
    required double z,
    required double height,
    required double charWidth,
    required Mat mat,
    double spacing = .08,
    double spaceWidth = .45,
    double depth = .025,
    double ry = 0}) {
  final chars = text.runes.map(String.fromCharCode).toList();
  final advances = [
    for (final char in chars)
      char == ' ' ? charWidth * spaceWidth : charWidth + height * spacing,
  ];
  final totalWidth = advances.fold<double>(0, (a, b) => a + b) -
      (chars.isEmpty || chars.last == ' ' ? 0 : height * spacing);
  var cursor = -totalWidth / 2;
  final cellY = height / 16;
  final cellX = charWidth / 16;
  final base = trs(x, y, z, 0, ry);

  for (var ci = 0; ci < chars.length; ci++) {
    final char = chars[ci];
    final rows = _glyphs[char];
    if (rows != null) {
      for (var row = 0; row < 16; row++) {
        final bits = rows[row];
        var col = 0;
        while (col < 16) {
          while (col < 16 && (bits & (1 << (15 - col))) == 0) {
            col++;
          }
          final start = col;
          while (col < 16 && (bits & (1 << (15 - col))) != 0) {
            col++;
          }
          if (start == col) continue;
          final run = col - start;
          final localX = cursor + (start + run / 2) * cellX;
          final localY = height / 2 - (row + .5) * cellY;
          out.add(Part(boxGeometry(run * cellX, cellY * .92, depth),
              base * trs(localX, localY), mat));
        }
      }
    }
    cursor += advances[ci];
  }
}
